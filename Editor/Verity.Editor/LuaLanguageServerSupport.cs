    }

    private static void AppendClass(StringBuilder sb, string name, IEnumerable<(string Name, string Type)>? fields = null)
    {
        sb.AppendLine($"---@class {name}");
        if (fields != null)
        {
            foreach (var (fieldName, fieldType) in fields)
                sb.AppendLine($"---@field {fieldName} {fieldType}");
        }
        sb.AppendLine($"local {name} = {{}}");
    }

    private static void AppendComponentAlias(StringBuilder sb, IEnumerable<Type>? componentTypes)
    {
        var names = (componentTypes ?? Enumerable.Empty<Type>())
            .Where(static type => typeof(Component).IsAssignableFrom(type) && !type.IsAbstract)
            .SelectMany(static type => new[] { type.Name, type.FullName })
            .Where(static name => !string.IsNullOrWhiteSpace(name))
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .OrderBy(static name => name, StringComparer.OrdinalIgnoreCase)
            .ToArray();

        if (names.Length == 0)
        {
            sb.AppendLine("---@alias VerityComponentType string");
            sb.AppendLine();
            return;
        }

        sb.AppendLine("---@alias VerityComponentType");
        for (int i = 0; i < names.Length; i++)
            sb.AppendLine($"---| \"{EscapeLuaString(names[i]!)}\"");
        sb.AppendLine();
    }

    private static void AppendKeysClass(StringBuilder sb)
    {
        sb.AppendLine("---@class VerityKeys");
        foreach (string name in Enum.GetNames(typeof(Verity.Input.KeyCode)))
            sb.AppendLine($"---@field {name} integer");
        sb.AppendLine("local VerityKeys = {}");
        sb.AppendLine();
    }

    private static string EscapeLuaString(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");
}
