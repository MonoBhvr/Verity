        sb.AppendLine("function VerityScriptContext:StopAllCoroutines() end");
        sb.AppendLine();

        AppendClass(sb, "VerityTime", new[] { ("DeltaTime", "number"), ("TotalTime", "number"), ("LogicTickCount", "integer"), ("PhysicsTickCount", "integer") });
