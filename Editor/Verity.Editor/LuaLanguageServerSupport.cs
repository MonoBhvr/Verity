internal static class LuaLanguageServerSupport
{
    private static readonly JsonSerializerOptions JsonOptions = new() { WriteIndented = true };

    public static void EnsureProjectSupport(string? projectPath, IEnumerable<Type>? componentTypes)
    {
        if (string.IsNullOrWhiteSpace(projectPath))
            return;

        string normalizedProjectPath = Path.GetFullPath(projectPath);
        string supportRoot = Path.Combine(normalizedProjectPath, ".verity", "lua");
        string vscodeRoot = Path.Combine(normalizedProjectPath, ".vscode");

        Directory.CreateDirectory(supportRoot);
        Directory.CreateDirectory(vscodeRoot);

        File.WriteAllText(Path.Combine(supportRoot, "verity_api.lua"), BuildApiStub(componentTypes));
        File.WriteAllText(Path.Combine(vscodeRoot, "verity-lua.code-snippets"), BuildWorkspaceSnippets());
        WriteLuaRc(normalizedProjectPath);
    }

    private static void WriteLuaRc(string projectPath)
    {
        string luaRcPath = Path.Combine(projectPath, ".luarc.json");
        JsonObject root = File.Exists(luaRcPath)
            ? JsonNode.Parse(File.ReadAllText(luaRcPath)) as JsonObject ?? []
            : [];

        root["$schema"] = "https://raw.githubusercontent.com/LuaLS/vscode-lua/master/setting/schema.json";

        JsonObject workspace = EnsureObject(root, "workspace");
        EnsureStringArrayContains(workspace, "library", ".verity/lua");
        workspace["checkThirdParty"] = false;

        JsonObject runtime = EnsureObject(root, "runtime");
        runtime["version"] = "Lua 5.4";

        JsonObject completion = EnsureObject(root, "completion");
        completion["keywordSnippet"] = "Replace";

        JsonObject diagnostics = EnsureObject(root, "diagnostics");
        foreach (string global in new[] { "self", "Owner", "Time", "Input", "Keys", "Entity", "Vector2", "Vector3", "Wait", "WaitForSeconds", "WaitForTicks", "WaitForPhysicalTicks", "WaitUntil", "WaitWhile" })
            EnsureStringArrayContains(diagnostics, "globals", global);

        File.WriteAllText(luaRcPath, root.ToJsonString(JsonOptions));
    }

    private static JsonObject EnsureObject(JsonObject root, string name)
    {
        if (root[name] is JsonObject obj)
            return obj;

        obj = [];
        root[name] = obj;
        return obj;
    }

    private static void EnsureStringArrayContains(JsonObject root, string name, string value)
    {
        JsonArray array;
        if (root[name] is JsonArray existing)
        {
            array = existing;
        }
        else
        {
            array = [];
            root[name] = array;
        }

        if (!array.Any(node => string.Equals((string?)node, value, StringComparison.OrdinalIgnoreCase)))
            array.Add(value);
    }

    private static string BuildWorkspaceSnippets()
    {
        JsonObject root = new()
        {
            ["Verity Lua Behaviour"] = new JsonObject
            {
                ["prefix"] = "verity",
                ["body"] = new JsonArray
                {
                    "function Awake()",
                    "    $0",
                    "end",
                    "",
                    "function Start()",
                    "end",
                    "",
                    "function Update(deltaTime)",
                    "end"
                },
                ["description"] = "Verity Lua behaviour template"
            },
            ["Verity Coroutine"] = new JsonObject
            {
                ["prefix"] = "vcoroutine",
                ["body"] = new JsonArray
                {
                    "function ${1:RoutineName}()",
                    "    while true do",
                    "        ${2:-- body}",
                    "        coroutine.yield(Wait(${3:0.1}))",
                    "    end",
                    "end"
                },
                ["description"] = "Verity Lua coroutine template"
            }
        };

        return root.ToJsonString(JsonOptions);
    }

