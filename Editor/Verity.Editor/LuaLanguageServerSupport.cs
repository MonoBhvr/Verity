        sb.AppendLine("function Vector2(x, y) end");
        sb.AppendLine();

        AppendClass(sb, "VerityVector3", new[] { ("X", "number"), ("Y", "number"), ("Z", "number") });
        sb.AppendLine("---@param x number?");
        sb.AppendLine("---@param y number?");
        sb.AppendLine("---@param z number?");
        sb.AppendLine("---@return VerityVector3");
        sb.AppendLine("function Vector3(x, y, z) end");
